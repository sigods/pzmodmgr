struct Glyph {
    std::array<std::string_view, 16> rows;
};

template <typename Fn>
void visit(const Glyph& glyph, Fn&& fn) {
    for (int y = 0; y < 16; ++y) {
        const std::string_view row = glyph.rows[static_cast<std::size_t>(y)];
        for (int x = 0; x < 16 && x < static_cast<int>(row.size()); ++x)
            if (row[static_cast<std::size_t>(x)] == '#') fn(x, y);
    }
}

